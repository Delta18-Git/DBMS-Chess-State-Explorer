// One command for the whole local stack:   npm run setup
//
//   1. writes .env.local with random passwords if it does not exist
//   2. starts MySQL 8.4 + Neo4j in Podman (or Docker) and waits for both
//   3. creates the schema (or applies new migrations)
//   4. creates an admin and an analyst account (passwords saved outside the repo)
//   5. loads the opening catalogue, imports the bundled Lichess tournaments,
//      scores every position with Stockfish and builds the Neo4j graph
//
// Every data step calls the app's own API route handlers in-process, so it goes through the same
// validation, authorization and transactions as the web UI, without needing a running server.
//
// Other commands:  npm run setup -- up | down | status        (containers only; `npm run dev` runs `up`)
//                  npm run setup -- --fresh                   (drop and recreate both databases first)
//                  npm run setup -- --schema-only             (no data; used for the test database)
//                  npm run setup -- --env .env.test.local     (another environment file)
//                  npm run setup -- --depth 16                (Stockfish search depth, default 12)
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { readdir, readFile } from "node:fs/promises";
import { availableParallelism, homedir } from "node:os";
import { join } from "node:path";
import mysql from "mysql2/promise";

const args = process.argv.slice(2);
const flag = (name: string) => args.includes(name);
const option = (name: string, fallback: string) => { const i = args.indexOf(name); return i >= 0 && args[i + 1] ? args[i + 1] : fallback; };
const command = args.find(a => ["up", "down", "status"].includes(a)) ?? "setup";
const quiet = flag("--quiet");
const log = (...m: unknown[]) => { if (!quiet) console.log(...m); };
const step = (m: string) => log(`\n▸ ${m}`);
const root = process.cwd(); // npm runs scripts from the package root


// ---------- environment ----------
const envFile = option("--env", ".env.local");
function loadEnv(file: string) {
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = /^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
if (!existsSync(envFile)) {
  if (envFile !== ".env.local") throw new Error(`${envFile} not found`);
  const secret = () => randomBytes(18).toString("base64url");
  writeFileSync(envFile, [
    "# Generated by npm run setup. Local only: never commit.",
    "DB_HOST=127.0.0.1", "DB_PORT=3307", "DB_NAME=chess_intel", "DB_USER=chess_app", `DB_PASSWORD=${secret()}`,
    `MYSQL_ROOT_PASSWORD=${secret()}`,
    "NEO4J_URI=bolt://127.0.0.1:7688", "NEO4J_USER=neo4j", `NEO4J_PASSWORD=${secret()}`, "NEO4J_HTTP_PORT=7475", "",
  ].join("\n"), { mode: 0o600 });
  log(`Created ${envFile} with random passwords.`);
}
loadEnv(envFile);
const env = process.env as Record<string, string>;
const local = ["127.0.0.1", "localhost"].includes(env.DB_HOST);

// ---------- containers ----------
const engine = env.CONTAINER_ENGINE || ["podman", "docker"].find(e => spawnSync(e, ["--version"], { stdio: "ignore" }).status === 0);
const run = (cmd: string[], show = false) => spawnSync(engine!, cmd, { stdio: show ? "inherit" : "pipe", encoding: "utf8" });
// Container names can be overridden (the test stack shares chess-mysql but has its own Neo4j).
const MYSQL = env.MYSQL_CONTAINER || "chess-mysql", NEO4J = env.NEO4J_CONTAINER || "chess-neo4j";
const suffix = env.DB_NAME.endsWith("_test") ? "-test" : "";
const exists = (name: string) => run(["container", "inspect", name]).status === 0;
const boltPort = env.NEO4J_URI.split(":").pop()!;

async function waitFor(what: string, ok: () => boolean | Promise<boolean>) {
  for (let i = 0; i < 90; i++) { if (await ok()) return; await new Promise(r => setTimeout(r, 2000)); }
  throw new Error(`${what} did not become ready`);
}

async function up() {
  if (!local) { log("DB_HOST is not local: skipping containers."); return; }
  if (!engine) throw new Error("Install podman (or docker), or point DB_HOST/NEO4J_URI at running servers.");
  if (!exists(MYSQL)) {
    log(`Creating container ${MYSQL} (MySQL 8.4) on 127.0.0.1:${env.DB_PORT}`);
    run(["run", "-d", "--name", MYSQL, "-e", `MYSQL_DATABASE=${env.DB_NAME}`, "-e", `MYSQL_USER=${env.DB_USER}`,
      "-e", `MYSQL_PASSWORD=${env.DB_PASSWORD}`, "-e", `MYSQL_ROOT_PASSWORD=${env.MYSQL_ROOT_PASSWORD}`,
      "-p", `127.0.0.1:${env.DB_PORT}:3306`, "-v", `${MYSQL.replace(/-/g, "_")}_data:/var/lib/mysql`,
      "docker.io/library/mysql:8.4", "--log-bin-trust-function-creators=1"], true);
  } else run(["start", MYSQL]);
  if (!exists(NEO4J)) {
    log(`Creating container ${NEO4J} (Neo4j) on bolt ${boltPort}, browser ${env.NEO4J_HTTP_PORT ?? 7475}`);
    run(["run", "-d", "--name", NEO4J, "-e", `NEO4J_AUTH=${env.NEO4J_USER}/${env.NEO4J_PASSWORD}`,
      "-p", `127.0.0.1:${env.NEO4J_HTTP_PORT ?? "7475"}:7474`, "-p", `127.0.0.1:${boltPort}:7687`,
      "-v", `${NEO4J.replace(/-/g, "_")}_data:/data`, "docker.io/library/neo4j:community"], true);
  } else run(["start", NEO4J]);
  await waitFor("MySQL", () => run(["exec", MYSQL, "mysqladmin", "ping", "-h", "127.0.0.1", "-uroot", `-p${env.MYSQL_ROOT_PASSWORD}`, "--silent"]).status === 0);
  await waitFor("Neo4j", () => run(["exec", NEO4J, "cypher-shell", "-u", env.NEO4J_USER, "-p", env.NEO4J_PASSWORD, "RETURN 1"]).status === 0);
  log(`MySQL 127.0.0.1:${env.DB_PORT} · Neo4j ${env.NEO4J_URI} · Neo4j Browser http://127.0.0.1:${env.NEO4J_HTTP_PORT ?? 7475}`);
}

// ---------- schema ----------
async function connect(multipleStatements = false) {
  const { dbOptions } = await import("../src/lib/db");
  return mysql.createConnection({ ...dbOptions(), multipleStatements });
}

/** Applies database/migrations/*.sql in name order, exactly once each (recorded in schema_migration). */
async function migrate(connection: mysql.Connection) {
  await connection.query(`CREATE TABLE IF NOT EXISTS schema_migration (
    name VARCHAR(100) PRIMARY KEY, applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB`);
  const [done] = await connection.query<mysql.RowDataPacket[]>("SELECT name FROM schema_migration");
  const applied = new Set(done.map(r => r.name as string));
  const ran: string[] = [];
  for (const file of (await readdir("database/migrations")).filter(f => f.endsWith(".sql")).sort()) {
    if (applied.has(file)) continue;
    // MySQL DDL commits implicitly: a migration is recorded only after it fully succeeds.
    await connection.query(await readFile(join("database/migrations", file), "utf8"));
    await connection.execute("INSERT INTO schema_migration (name) VALUES (?)", [file]);
    ran.push(file);
  }
  return ran;
}

/** Root-level SQL inside the local MySQL container (database creation only; the app never uses root). */
function asRoot(sql: string) {
  if (!/^[A-Za-z0-9_]+$/.test(env.DB_NAME) || !/^[A-Za-z0-9_]+$/.test(env.DB_USER)) throw new Error("DB_NAME/DB_USER must be plain identifiers");
  const r = run(["exec", MYSQL, "mysql", "-uroot", `-p${env.MYSQL_ROOT_PASSWORD}`, "-e", sql]);
  if (r.status !== 0) throw new Error(`MySQL (root) failed: ${r.stderr.replace(/.*Using a password.*\n?/g, "").trim()}`);
}
const CREATE_DB = () => `CREATE DATABASE IF NOT EXISTS \`${env.DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
  GRANT ALL ON \`${env.DB_NAME}\`.* TO '${env.DB_USER}'@'%';`;

async function fresh() {
  step("Dropping and recreating the database (--fresh); the graph is rebuilt from it below");
  if (!local) throw new Error("--fresh only runs against local containers");
  asRoot(`DROP DATABASE IF EXISTS \`${env.DB_NAME}\`; ${CREATE_DB()}`);
}

async function schema() {
  const connection = await connect(true);
  try {
    const [tables] = await connection.query<mysql.RowDataPacket[]>("SHOW TABLES");
    if (!tables.length) {
      step("Creating schema, views, procedure, triggers");
      await connection.query(await readFile("database/schema.sql", "utf8"));
      await connection.beginTransaction();
      try { await connection.query(await readFile("database/seed.sql", "utf8")); await connection.commit(); }
      catch (error) { await connection.rollback(); throw error; }
    }
    const ran = await migrate(connection);
    if (ran.length) log(`  migrations applied: ${ran.join(", ")}`);
  } finally { await connection.end(); }
}

// ---------- accounts & an in-process API session ----------
async function accounts() {
  const { hashPassword } = await import("../src/lib/auth");
  const connection = await connect();
  try {
    const [[{ n }]] = await connection.query<mysql.RowDataPacket[]>("SELECT COUNT(*) AS n FROM app_user");
    if (Number(n) > 0) return;
    step("Creating accounts");
    const people = [
      // Nothing personal is hard-coded: override any of these in .env.local before the first setup.
      { email: env.ADMIN_EMAIL || "admin@chess.local", name: env.ADMIN_NAME || "Admin", role: "admin" },
      { email: env.ANALYST_EMAIL || "analyst@chess.local", name: env.ANALYST_NAME || "Analyst", role: "analyst" },
    ];
    const lines = ["# Chess State Explorer local accounts (generated by npm run setup)"];
    for (const p of people) {
      const password = (p.role === "admin" ? env.ADMIN_PASSWORD : env.ANALYST_PASSWORD) || randomBytes(9).toString("base64url");
      await connection.execute("INSERT INTO app_user (email, display_name, password_hash, role) VALUES (?, ?, ?, ?)",
        [p.email, p.name, await hashPassword(password), p.role]);
      lines.push(`${p.role.padEnd(8)} ${p.email}  ${password}`);
    }
    const dir = join(homedir(), ".config", "chess-state-explorer");
    mkdirSync(dir, { recursive: true });
    const file = join(dir, `accounts${suffix}.txt`);
    writeFileSync(file, lines.join("\n") + "\n", { mode: 0o600 });
    log(lines.slice(1).map(l => `  ${l}`).join("\n"));
    log(`  saved to ${file}`);
  } finally { await connection.end(); }
}

/** A short-lived admin session so setup can call the route handlers like any API client. */
async function session() {
  const { newToken, tokenHash } = await import("../src/lib/auth");
  const connection = await connect();
  const token = newToken();
  await connection.execute(
    `INSERT INTO api_session (token_hash, user_id, expires_at)
     SELECT ?, user_id, DATE_ADD(UTC_TIMESTAMP(), INTERVAL 3 HOUR) FROM app_user WHERE role = 'admin' ORDER BY user_id LIMIT 1`,
    [tokenHash(token)],
  );
  await connection.end();
  return token;
}

async function call(token: string, method: "GET" | "POST", path: string, data?: unknown) {
  const [pathname, query = ""] = path.split("?");
  const parts = pathname.split("/").filter(Boolean);
  const dynamicId = parts.find(p => /^\d+$/.test(p));
  const file = join(root, "src/app/api", ...parts.map(p => (/^\d+$/.test(p) ? "[id]" : p)), "route.ts");
  const route = await import(file);
  const request = new Request(`http://setup/api/${pathname}${query ? `?${query}` : ""}`, {
    method, headers: { authorization: `Bearer ${token}`, ...(data ? { "content-type": "application/json" } : {}) },
    ...(data ? { body: JSON.stringify(data) } : {}),
  });
  const response: Response = await route[method](request, { params: Promise.resolve({ id: dynamicId ?? "" }) });
  const payload = await response.json() as { data?: any; error?: { message: string } };
  if (!response.ok) throw new Error(`${method} /api/${path} → ${response.status}: ${payload.error?.message}`);
  return payload.data;
}

// ---------- data ----------
async function data() {
  const token = await session();
  const connection = await connect();
  try {
    step("Loading the Lichess opening catalogue");
    const cat = await call(token, "POST", "openings/catalogue");
    log(`  ${cat.named_openings} named openings over ${cat.boards} boards`);

    step("Importing Lichess broadcast tournaments");
    for (const file of (await readdir("data/lichess")).filter(f => /^[A-Za-z0-9]{8}\.json$/.test(f)).sort()) {
      const r = await call(token, "POST", "import/lichess", { source: file.slice(0, 8) });
      log(`  ${r.tournament}: ${r.imported} games${r.duplicates ? `, ${r.duplicates} already stored` : ""}${r.failed.length ? `, ${r.failed.length} rejected` : ""}`);
    }

    step("Scoring positions with Stockfish");
    // A native binary (e.g. from the conda env) is ~1.5x faster; npm's node_modules/.bin wrapper is the WASM build.
    const native = env.STOCKFISH_PATH || spawnSync("sh", ["-c", "which -a stockfish 2>/dev/null"], { encoding: "utf8" }).stdout
      .split("\n").find(p => p && !p.includes("node_modules")) || "";
    if (native) process.env.STOCKFISH_PATH = native;
    process.env.ENGINE_WORKERS ||= String(Math.max(2, Math.min(16, Math.floor(availableParallelism() / 2))));
    log(`  engine: ${native ? `native ${native}` : "bundled WebAssembly build"}, ${process.env.ENGINE_WORKERS} parallel processes`);
    const depth = Number(option("--depth", "12"));
    const [[{ todo }]] = await connection.query<mysql.RowDataPacket[]>(
      "SELECT COUNT(*) AS todo FROM `position` p WHERE NOT EXISTS (SELECT 1 FROM evaluation e WHERE e.position_id = p.position_id) AND EXISTS (SELECT 1 FROM ply m WHERE m.to_position_id = p.position_id OR m.from_position_id = p.position_id)",
    );
    let scored = 0;
    const started = Date.now();
    while (true) {
      const r = await call(token, "POST", "engine/analyse", { depth, limit: 1000 });
      scored += r.scored;
      if (r.scored) log(`  ${scored} / ~${todo} boards (${Math.round((Date.now() - started) / 1000)}s)`);
      if (!r.remaining) break;
    }

    // Bulk upserts can leave InnoDB FULLTEXT indexes incomplete; rebuilding the three searched
    // tables (OPTIMIZE = recreate + analyze for InnoDB) makes every name searchable.
    step("Rebuilding full-text indexes");
    await connection.query("OPTIMIZE TABLE player, opening, tournament");

    step("Building the Neo4j graph from MySQL");
    const g = await call(token, "POST", "graph/sync?mode=rebuild");
    log(`  ${g.edges} move edges`);

    step("Building example repertoires from players' own games");
    const [[{ reps }]] = await connection.query<mysql.RowDataPacket[]>("SELECT COUNT(*) AS reps FROM repertoire");
    if (!Number(reps)) {
      const [top] = await connection.query<mysql.RowDataPacket[]>(
        `SELECT p.player_id, p.name, v.color, COUNT(*) AS games FROM v_player_game v JOIN player p ON p.player_id = v.player_id
         GROUP BY p.player_id, p.name, v.color ORDER BY games DESC, p.rating DESC LIMIT 4`,
      );
      for (const t of top) {
        const name = `${String(t.name).split(",")[0]} as ${t.color === "w" ? "White" : "Black"}`;
        const rep = await call(token, "POST", "repertoires", { player_id: Number(t.player_id), name, color: t.color });
        const built = await call(token, "POST", `repertoires/${rep.repertoire_id}/build`, { moves: 10, min_games: 1 });
        log(`  ${name}: ${built.added} prepared moves`);
      }
    }
  } finally {
    const { tokenHash } = await import("../src/lib/auth");
    await connection.execute("DELETE FROM api_session WHERE token_hash = ?", [tokenHash(token)]);
    await connection.end();
    const { closeGraph } = await import("../src/lib/graph");
    await closeGraph();
    const { getPool } = await import("../src/lib/db");
    await getPool().end();
  }
}

async function main() {
  if (command === "down") { run(["stop", MYSQL, NEO4J], true); return; }
  if (command === "status") { run(["ps", "-a", "--filter", "name=chess-"], true); return; }
  await up();
  if (command === "up") return;
  if (flag("--fresh")) await fresh();
  else if (local && engine) asRoot(CREATE_DB());
  await schema();
  await accounts();
  if (flag("--schema-only")) { log("\nSchema ready (no data loaded)."); return; }
  await data();
  log("\n✓ Ready. Start the app with  npm run dev  and open http://localhost:3000");
}
main().catch(error => {
  console.error(`\n✗ ${error instanceof Error ? error.message : error}`);
  process.exitCode = 1;
});
